#!/usr/bin/env python3
"""Builds supabase/seed/sample.sql from the handoff's sample data (supabase/seed/handoff/*.json).

Run:  python3 scripts/seed/build_sample_sql.py
Then run the SQL against the database. Running it again changes nothing: every row has a stable
id derived from the handoff's own string id (UUID v5), and inserts skip rows that already exist.

Everything it creates is flagged as sample and can be removed with supabase/seed/remove_sample.sql.
Sample accounts get no password, so nobody can sign in as them.

Only what today's tables can hold is loaded. Businesses, stories, blogs and the rest are added
to this script in the phase that builds their tables.
"""
import json
import re
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "supabase" / "seed" / "handoff"
OUT = ROOT / "supabase" / "seed" / "sample.sql"
NS = uuid.UUID("5b1d2c84-6d0e-4f43-9a1e-2f3c5e7d9a10")  # fixed: the same input always gives the same id

def sid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))

def q(value) -> str:
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"

def slugify(name: str) -> str:
    s = name.lower().replace("&", "and")
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")

def email(member_id: str) -> str:
    return f"{member_id}@demo.invalid"

PLAN = {"Advisor": "advisor", "Plus": "plus"}
MEMBER_TYPE = {"advisor": "advisor", "plus": "plus", "free": "owner"}

def load(name):
    return json.loads((DATA / name).read_text())

def main():
    members = load("01_members.json")
    feed = load("02_feed_posts.json")
    groups = load("03_groups.json")
    photos = {p.stem[2:] for p in (ROOT / "public" / "sample").glob("p-*.jpg")}

    people = list(members["MEMBERS"]) + [members["XM"]["spam1"], members["XM"]["spam2"]]
    about = members.get("ABOUT", {})
    ids = [m["id"] for m in people]
    rows = lambda items: ",\n  ".join("(" + ", ".join(q(v) if not isinstance(v, bool) else str(v).lower() for v in it) + ")" for it in items)
    sql = ["-- Generated by scripts/seed/build_sample_sql.py from the handoff sample data. Do not edit by hand.",
           "begin;", ""]

    # ---------- members: accounts (no password, cannot sign in) then their profiles ----------
    member_rows = []
    for m in people:
        plan = PLAN.get(m.get("plan", ""), "free")
        avatar = f"/sample/p-{m['id']}.jpg" if m["id"] in photos else None
        member_rows.append((m["id"], sid("member", m["id"]), email(m["id"]), m["name"], m.get("role", ""), m.get("city", ""),
                            about.get(m["id"], ""), plan, MEMBER_TYPE[plan], avatar))
    sql.append("create temp table s_members (key text, id uuid, email text, name text, headline text, city text, bio text, "
               "plan text, member_type text, avatar text) on commit drop;")
    sql.append("insert into s_members values\n  " + rows(member_rows) + ";")
    sql.append(
        "insert into auth.users (instance_id, id, aud, role, email, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, "
        "confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current, phone_change, "
        "phone_change_token, reauthentication_token)\n"
        "select '00000000-0000-0000-0000-000000000000', s.id, 'authenticated', 'authenticated', s.email, "
        "'{\"provider\": \"email\", \"providers\": [\"email\"], \"sample\": true}'::jsonb, jsonb_build_object('full_name', s.name), "
        "now(), now(), '', '', '', '', '', '', '', ''\n"
        "from s_members s where not exists (select 1 from auth.users u where u.email = s.email);")
    sql.append("update auth.users set raw_app_meta_data = coalesce(raw_app_meta_data, '{}'::jsonb) || '{\"sample\": true}' "
               "where email like '%@demo.invalid';")
    sql.append("update profiles p set is_sample = true, founding_number = null, full_name = s.name, headline = s.headline, "
               "location = s.city, bio = s.bio, plan = s.plan, member_type = s.member_type, avatar_url = s.avatar\n"
               "from s_members s join auth.users u on u.email = s.email where p.id = u.id;")
    # ---------- profile type, helps with, looking for and availability (Phase 2) ----------
    avail = members.get("AVAIL", {})
    type_of = {"makers": "maker", "account": "provider", "legal": "provider", "design": "provider", "trades": "provider", "logistics": "provider"}
    arr = lambda items: "array[" + ", ".join(q(i) for i in items) + "]::text[]" if items else "'{}'::text[]"
    detail_rows = []
    for m in people:
        detail_rows.append((m["id"], type_of.get(m.get("is", ""), "owner"), arr(m.get("helps", [])), arr(m.get("needs", [])), arr(avail.get(m["id"], []))))
    sql.append("create temp table s_details (key text, ptype text, helps text[], needs text[], avail text[]) on commit drop;")
    sql.append("insert into s_details values\n  " + ",\n  ".join(f"({q(k)}, {q(t)}, {h}, {n}, {a})" for k, t, h, n, a in detail_rows) + ";")
    sql.append("update profiles p set profile_type = d.ptype from s_details d join s_members s on s.key = d.key "
               "join auth.users u on u.email = s.email where p.id = u.id;")
    sql.append("insert into profile_details (user_id, helps_with, needs, availability)\n"
               "select u.id, d.helps, d.needs, d.avail from s_details d join s_members s on s.key = d.key join auth.users u on u.email = s.email\n"
               "on conflict (user_id) do nothing;")
    sql.append("create temp table s_ids on commit drop as select s.key, u.id from s_members s join auth.users u on u.email = s.email;")

    # ---------- groups and members ----------
    meta = groups.get("GMETA", {})
    group_rows, join_rows = [], []
    for g in groups["GROUPS"]:
        owner = (meta.get(g["id"]) or [None, None, None])[2] or "priya"
        private = (meta.get(g["id"]) or [""])[0] == "Private circle"
        group_rows.append((sid("group", g["id"]), slugify(g["name"]), g["name"], g.get("desc", ""), private, owner))
        size = max(1, min(int(g.get("n", 5)), len(ids)))
        start = ids.index(owner) if owner in ids else 0
        for k in range(1, size):
            who = ids[(start + k) % len(ids)]
            if not who.startswith("spam"):
                join_rows.append((slugify(g["name"]), who))
    sql.append("")
    sql.append("insert into groups (id, slug, name, description, is_private, created_by, is_sample)\n"
               "select v.id::uuid, v.slug, v.name, v.description, v.private, i.id, true from (values\n  " + rows(group_rows) +
               "\n) v(id, slug, name, description, private, owner) join s_ids i on i.key = v.owner\n"
               "on conflict (slug) do update set is_sample = true;")
    sql.append("insert into group_members (group_id, user_id)\nselect g.id, i.id from (values\n  " + rows(join_rows) +
               "\n) v(slug, who) join groups g on g.slug = v.slug join s_ids i on i.key = v.who on conflict do nothing;")

    # ---------- posts, comments and likes (business posts wait for Phase 4) ----------
    slug_of = {g["id"]: slugify(g["name"]) for g in groups["GROUPS"]}
    post_rows, comment_rows, like_rows = [], [], []
    for p in feed["posts"]:
        if p["by"] not in ids or p.get("kind") == "biz":
            continue
        kind = p.get("kind") if p.get("kind") in ("question", "win", "offer", "hiring", "intro") else "update"
        photo = (p.get("photo") or "").replace("img/", "/sample/") or None
        hours = int(float(p.get("t") or 1) * 24)
        post_rows.append((sid("post", p["id"]), p["by"], slug_of.get(p.get("g")), p["text"], photo, kind, str(hours)))
        for i, c in enumerate(p.get("comments", [])):
            if c["by"] in ids:
                comment_rows.append((sid("comment", f"{p['id']}:{i}"), sid("post", p["id"]), c["by"], c["text"], str(max(1, hours - i - 1))))
        for who in [x for x in ids if x != p["by"] and not x.startswith("spam")][: int(p.get("helpful") or 0)]:
            like_rows.append((sid("post", p["id"]), who))
    sql.append("")
    sql.append("insert into posts (id, author_id, group_id, body, image_url, kind, visibility, created_at, is_sample)\n"
               "select v.id::uuid, i.id, g.id, v.body, v.image, v.kind, 'public', now() - (v.hours || ' hours')::interval, true from (values\n  " +
               rows(post_rows) + "\n) v(id, who, slug, body, image, kind, hours) join s_ids i on i.key = v.who "
               "left join groups g on g.slug = v.slug on conflict (id) do nothing;")
    sql.append("insert into comments (id, post_id, author_id, body, created_at, is_sample)\n"
               "select v.id::uuid, v.post::uuid, i.id, v.body, now() - (v.hours || ' hours')::interval, true from (values\n  " +
               rows(comment_rows) + "\n) v(id, post, who, body, hours) join s_ids i on i.key = v.who on conflict (id) do nothing;")
    sql.append("insert into reactions (post_id, user_id, kind)\nselect v.post::uuid, i.id, 'like' from (values\n  " +
               rows(like_rows) + "\n) v(post, who) join s_ids i on i.key = v.who on conflict do nothing;")

    sql += ["", "commit;", ""]
    OUT.write_text("\n".join(sql))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(sql)} lines)")

if __name__ == "__main__":
    main()
