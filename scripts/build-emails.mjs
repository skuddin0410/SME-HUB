// Turns the handoff's emails/ folder into TypeScript modules the server can bundle.
// Run after changing emails/templates, emails/text or emails/emails.json:  node scripts/build-emails.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../emails/", import.meta.url).pathname;
const out = new URL("../lib/email/generated/", import.meta.url).pathname;
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

// emails.json is the handoff catalogue as supplied; extra.json holds emails we added for flows the handoff does not cover
const catalogue = [...JSON.parse(readFileSync(join(root, "emails.json"), "utf8")), ...JSON.parse(readFileSync(join(root, "extra.json"), "utf8"))];
const ids = catalogue.map((e) => e.id);
const files = readdirSync(join(root, "templates")).map((f) => f.replace(/\.html$/, "")).sort();
const missing = ids.filter((i) => !files.includes(i));
if (missing.length) throw new Error("Templates missing for: " + missing.join(", "));

for (const id of ids) {
  const html = readFileSync(join(root, "templates", id + ".html"), "utf8");
  const text = readFileSync(join(root, "text", id + ".txt"), "utf8");
  writeFileSync(join(out, id + ".ts"), `// generated by scripts/build-emails.mjs. Do not edit.\nexport const html = ${JSON.stringify(html)};\nexport const text = ${JSON.stringify(text)};\n`);
}

writeFileSync(
  join(out, "catalogue.ts"),
  `// generated by scripts/build-emails.mjs. Do not edit.\nexport type CatalogueEntry = {\n  id: string; category: string; name: string; trigger: string; sender: string; subject: string; preheader: string; type: string;\n  preview_subject: string; preview_preheader: string; variables: string[]; lists: string[]; list_fields: string[]; size_kb: number;\n};\nexport const CATALOGUE: CatalogueEntry[] = ${JSON.stringify(catalogue, null, 1)};\n`,
);
writeFileSync(
  join(out, "loaders.ts"),
  `// generated by scripts/build-emails.mjs. Do not edit.\nexport const LOADERS: Record<string, () => Promise<{ html: string; text: string }>> = {\n${ids.map((i) => `  ${JSON.stringify(i)}: () => import("./${i}"),`).join("\n")}\n};\n`,
);
console.log(`wrote ${ids.length} emails`);
