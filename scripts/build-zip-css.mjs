// Scopes the design guide's stylesheet (design/zip-source.css, copied unchanged from the handoff zip)
// under a .zip wrapper so it can sit beside the rest of the site. Run: node scripts/build-zip-css.mjs
import postcss from "postcss";
import fs from "node:fs";

const src = fs.readFileSync("design/zip-source.css", "utf8");
const scope = (sel) => {
  sel = sel.trim();
  if (sel === ":root" || sel === "html" || sel === "body" || sel === "html,body") return ".zip";
  if (sel === ":root.dark" || sel === "html.dark") return ".dark .zip, .zip.dark";
  if (sel === "*") return ".zip, .zip *";
  if (sel === ":root.dark body" || sel === "html.dark body") return ".dark .zip";
  if (sel.startsWith(":root.dark body ")) return `.dark .zip ${sel.slice(16)}`;
  if (sel.startsWith(":root.dark ")) return `.dark .zip ${sel.slice(11)}`;
  if (sel.startsWith("html.dark ")) return `.dark .zip ${sel.slice(10)}`;
  if (sel.startsWith("body.")) return `.zip.${sel.slice(5)}`;
  if (sel.startsWith(".dark ")) return `.dark .zip ${sel.slice(6)}`;
  if (sel.startsWith("::") || sel.startsWith("@")) return sel;
  return `.zip ${sel}`;
};
const root = postcss.parse(src);
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.flatMap((s) => scope(s).split(/,(?![^(]*\))/).map((x) => x.trim()));
});
fs.writeFileSync("styles/zip.css", "/* generated by scripts/build-zip-css.mjs from design/zip-source.css, do not edit */\n" + root.toString());
console.log("ok");
